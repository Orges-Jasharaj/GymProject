CREATE TABLE FitnessPlans
(
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL,
    Name NVARCHAR(100) NOT NULL,
    Description NVARCHAR(500) NULL,
    CreatedBy NVARCHAR(450) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedBy NVARCHAR(450) NULL,
    UpdatedAt DATETIME2 NULL,
    
    FOREIGN KEY (UserId) REFERENCES UserProfiles(Id)
);

CREATE TABLE Exercises
(
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL,
    Description NVARCHAR(500) NULL,
    MuscleGroup NVARCHAR(50) NULL,
    Equipment NVARCHAR(50) NULL,
    CreatedBy NVARCHAR(450) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedBy NVARCHAR(450) NULL,
    UpdatedAt DATETIME2 NULL
);

CREATE TABLE PlanExercises
(
    Id UNIQUEIDENTIFIER PRIMARY KEY,
    FitnessPlanId UNIQUEIDENTIFIER NOT NULL,
    ExerciseId UNIQUEIDENTIFIER NOT NULL,
    Sets INT NOT NULL DEFAULT 3,
    Reps INT NOT NULL DEFAULT 12,
    ExerciseOrder INT NOT NULL DEFAULT 1,
    CreatedBy NVARCHAR(450) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedBy NVARCHAR(450) NULL,
    UpdatedAt DATETIME2 NULL,

    FOREIGN KEY (FitnessPlanId) REFERENCES FitnessPlans(Id),
    FOREIGN KEY (ExerciseId) REFERENCES Exercises(Id)
)
